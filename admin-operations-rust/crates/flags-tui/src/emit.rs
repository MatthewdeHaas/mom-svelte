//! Migration-file emitter.
//!
//! Walks the `Grid` after the user hits `w`, diffs each cell against
//! the original snapshot, and produces a single SQL file in
//! `scripts/migrations/`. No diff → no file.
//!
//! File-name shape: `NNN_flags_<utc_timestamp>.sql`, where `NNN` is
//! one greater than the largest existing `NNN_*.sql` prefix. The
//! timestamp is `YYYYMMDDTHHMMSSZ` so the filename sorts
//! lexicographically within the same `NNN`.
//!
//! SQL shape (hybrid delta — only changed rows):
//! - New catalog flags not yet in `feature_flag`:
//!   `INSERT ... ON CONFLICT (name) DO NOTHING`
//! - Changed `enabled_global`: `UPDATE feature_flag SET ... WHERE name = ...`
//! - Added or flipped per-company override:
//!   `INSERT ... ON CONFLICT (flag_name, company_id) DO UPDATE SET enabled = EXCLUDED.enabled`
//! - Cleared per-company override (`Unset`): `DELETE FROM feature_flag_company WHERE ...`

use std::{
    fs,
    path::{Path, PathBuf},
};

use anyhow::{anyhow, Context, Result};
use chrono::{DateTime, Utc};

use crate::model::{CellState, Col, Grid};

/// Top-level emit entry point. Returns `None` when there are no
/// changes (caller prints "no changes" + exits cleanly), otherwise
/// returns the path of the written file.
pub fn emit(
    grid: &Grid,
    migrations_dir: &Path,
    now: DateTime<Utc>,
    snapshot_source: &str,
    operator_user_id: &str,
) -> Result<Option<PathBuf>> {
    let body = render_body(grid, now, snapshot_source, operator_user_id);
    if !has_changes(grid) {
        return Ok(None);
    }

    let next_num = next_migration_number(migrations_dir)
        .context("resolve next migration number")?;
    let filename = format!(
        "{:03}_flags_{}.sql",
        next_num,
        now.format("%Y%m%dT%H%M%SZ")
    );
    let path = migrations_dir.join(filename);

    fs::write(&path, body).with_context(|| format!("write migration to {}", path.display()))?;
    Ok(Some(path))
}

/// True iff any cell changed vs. snapshot, OR any catalog flag is
/// missing from the snapshot (needs an INSERT seed row).
fn has_changes(grid: &Grid) -> bool {
    if grid
        .rows
        .iter()
        .any(|d| !grid.snapshot_flags.contains_key(&d.name))
    {
        return true;
    }
    grid.cells
        .iter()
        .any(|(k, v)| grid.original.get(k) != Some(v))
}

/// Build the SQL body. Pure function — unit-testable without a tempdir.
pub fn render_body(
    grid: &Grid,
    now: DateTime<Utc>,
    snapshot_source: &str,
    operator_user_id: &str,
) -> String {
    let mut out = String::new();

    // Header.
    out.push_str(&format!(
        "-- flags migration — generated by flags-tui at {}\n",
        now.format("%Y-%m-%dT%H:%M:%SZ")
    ));
    out.push_str(&format!("-- Snapshot source: {snapshot_source}\n"));
    out.push_str(&format!("-- Signed by: {operator_user_id}\n"));
    out.push('\n');

    // Section 1 — new catalog flags not yet seeded in `feature_flag`.
    let new_flags: Vec<_> = grid
        .rows
        .iter()
        .filter(|d| !grid.snapshot_flags.contains_key(&d.name))
        .collect();
    if !new_flags.is_empty() {
        out.push_str("-- New flags discovered in catalog but not yet in DB:\n");
        for d in &new_flags {
            // Default from the compile-time catalog — same as what the
            // seed rows in migration 009 use. If the user flipped the
            // global cell before writing, Section 2's UPDATE will fix
            // it; keeping the seed row's default stable makes the
            // migration easier to read.
            let default = sql_bool(d.default);
            out.push_str(&format!(
                "INSERT INTO feature_flag (name, description, enabled_global)\n  \
                 VALUES ({}, {}, {})\n  \
                 ON CONFLICT (name) DO NOTHING;\n",
                sql_str(&d.name),
                sql_str(&d.description),
                default,
            ));
        }
        out.push('\n');
    }

    // Section 2 — global-default changes.
    let mut global_updates: Vec<(String, bool)> = Vec::new();
    for d in &grid.rows {
        let now_state = grid.global_of(&d.name);
        let was_state = grid
            .original
            .get(&(d.name.clone(), 0))
            .copied()
            .unwrap_or(CellState::False);
        // For a brand-new catalog flag (no snapshot row), Section 1 has
        // already inserted it at `d.default`. Only emit a Section 2
        // UPDATE if the user also changed the global cell away from
        // that default — otherwise it's a no-op line.
        let needs_update = if grid.snapshot_flags.contains_key(&d.name) {
            now_state != was_state
        } else {
            let default_cell = if d.default { CellState::True } else { CellState::False };
            now_state != default_cell
        };
        if needs_update {
            global_updates.push((d.name.clone(), matches!(now_state, CellState::True)));
        }
    }
    if !global_updates.is_empty() {
        out.push_str("-- Global default changes:\n");
        for (name, enabled) in &global_updates {
            out.push_str(&format!(
                "UPDATE feature_flag SET enabled_global = {} WHERE name = {};\n",
                sql_bool(*enabled),
                sql_str(name),
            ));
        }
        out.push('\n');
    }

    // Section 3 — per-company upserts and deletes.
    // Build a deterministic row order: iterate the catalog, then the
    // non-GLOBAL columns in grid order. That matches how the user sees
    // the grid, which keeps diffs stable across runs.
    let mut upserts: Vec<(String, uuid::Uuid, bool)> = Vec::new();
    let mut deletes: Vec<(String, uuid::Uuid)> = Vec::new();
    for d in &grid.rows {
        for (col_i, col) in grid.cols.iter().enumerate().skip(1) {
            let Col::Company { id, .. } = col else { continue };
            let key = (d.name.clone(), col_i);
            let now_state = grid.cells.get(&key).copied().unwrap_or(CellState::Unset);
            let was_state = grid.original.get(&key).copied().unwrap_or(CellState::Unset);
            if now_state == was_state {
                continue;
            }
            match now_state {
                CellState::True => upserts.push((d.name.clone(), *id, true)),
                CellState::False => upserts.push((d.name.clone(), *id, false)),
                CellState::Unset => deletes.push((d.name.clone(), *id)),
            }
        }
    }
    if !upserts.is_empty() || !deletes.is_empty() {
        out.push_str("-- Per-company overrides (upserts + deletes):\n");
        for (name, company_id, enabled) in &upserts {
            out.push_str(&format!(
                "INSERT INTO feature_flag_company (flag_name, company_id, enabled)\n  \
                 VALUES ({}, {}::uuid, {})\n  \
                 ON CONFLICT (flag_name, company_id) DO UPDATE SET enabled = EXCLUDED.enabled;\n",
                sql_str(name),
                sql_str(&company_id.to_string()),
                sql_bool(*enabled),
            ));
        }
        for (name, company_id) in &deletes {
            out.push_str(&format!(
                "DELETE FROM feature_flag_company\n  \
                 WHERE flag_name = {} AND company_id = {}::uuid;\n",
                sql_str(name),
                sql_str(&company_id.to_string()),
            ));
        }
        out.push('\n');
    }

    out
}

/// Scan `migrations_dir` for `NNN_*.sql` files and return the next
/// free number. Errors if the directory is missing — the TUI only
/// runs inside a checkout where `scripts/migrations/` exists.
fn next_migration_number(migrations_dir: &Path) -> Result<u32> {
    let read = fs::read_dir(migrations_dir).with_context(|| {
        format!(
            "read migrations dir {}",
            migrations_dir.display()
        )
    })?;

    let mut highest: u32 = 0;
    for entry in read {
        let entry = entry.context("read dir entry")?;
        let file_name = entry.file_name();
        let Some(name) = file_name.to_str() else { continue };
        if !name.ends_with(".sql") {
            continue;
        }
        // Prefix must be exactly 3 ASCII digits followed by `_` — matches
        // every migration in the repo today.
        let bytes = name.as_bytes();
        if bytes.len() < 4
            || !bytes[0].is_ascii_digit()
            || !bytes[1].is_ascii_digit()
            || !bytes[2].is_ascii_digit()
            || bytes[3] != b'_'
        {
            continue;
        }
        let num: u32 = name[..3].parse().map_err(|_| {
            anyhow!(
                "migration filename {} has non-numeric NNN prefix",
                name
            )
        })?;
        if num > highest {
            highest = num;
        }
    }
    Ok(highest + 1)
}

/// Postgres-safe single-quoted literal — doubles any embedded quote.
fn sql_str(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

fn sql_bool(b: bool) -> &'static str {
    if b {
        "TRUE"
    } else {
        "FALSE"
    }
}
